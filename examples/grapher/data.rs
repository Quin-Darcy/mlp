pub fn easy() -> DataSet {
    let samples: Vec<Array1<f32>> = EASY.iter().map(|(x, _)| array![*x]).collect();
    let labels: Vec<Array1<f32>> = EASY.iter().map(|(_, y)| array![*y]).collect();
    DataSet::from_data(samples, labels).unwrap()
}

pub fn hard() -> DataSet {
    let samples: Vec<Array1<f32>> = HARD.iter().map(|(x, _)| Array1::from(x.to_vec())).collect();
    let labels: Vec<Array1<f32>> = HARD.iter().map(|(_, y)| Array1::from(y.to_vec())).collect();
    DataSet::from_data(samples, labels).unwrap()
}
